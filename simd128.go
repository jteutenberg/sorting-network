// reverseRun16 reverses a sorted run of 16 that sits in two vectors.
func reverseRun16(lo, hi archsimd.Int32x8) (archsimd.Int32x8, archsimd.Int32x8) {
	return hi.Permute(laneReverse8), lo.Permute(laneReverse8)
}
