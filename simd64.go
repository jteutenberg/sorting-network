package sortingnetwork

import "simd/archsimd"

// SortingNetwork64BitonicSIMD sorts the 64 int32 channels at the front of data
// with a bitonic sorter. The channels stay in eight vectors for every layer:
// each layer has thirty-two comparators, so the comparison count never drops.
// Partners sit at distances 1, 2, 4, 8, 16, and 32. Distances 8 and up are
// cross-vector min/max of corresponding lanes; the shorter distances are the
// same in-vector shuffles as the size-16 sorter. The sorted values already
// land on channels 0..63, so there is no closing permute.
func SortingNetwork64BitonicSIMD(data []int32) {
	v0 := archsimd.LoadInt32x8(data)
	v1 := archsimd.LoadInt32x8(data[8:])
	v2 := archsimd.LoadInt32x8(data[16:])
	v3 := archsimd.LoadInt32x8(data[24:])
	v4 := archsimd.LoadInt32x8(data[32:])
	v5 := archsimd.LoadInt32x8(data[40:])
	v6 := archsimd.LoadInt32x8(data[48:])
	v7 := archsimd.LoadInt32x8(data[56:])

	// Block of 2. Direction alternates up, down, up, down inside every vector.
	v0 = compareDist1UDUD(v0)
	v1 = compareDist1UDUD(v1)
	v2 = compareDist1UDUD(v2)
	v3 = compareDist1UDUD(v3)
	v4 = compareDist1UDUD(v4)
	v5 = compareDist1UDUD(v5)
	v6 = compareDist1UDUD(v6)
	v7 = compareDist1UDUD(v7)

	// Block of 4. Low half of each vector sorts up, high half sorts down.
	v0 = compareDist2UUDD(v0)
	v1 = compareDist2UUDD(v1)
	v2 = compareDist2UUDD(v2)
	v3 = compareDist2UUDD(v3)
	v4 = compareDist2UUDD(v4)
	v5 = compareDist2UUDD(v5)
	v6 = compareDist2UUDD(v6)
	v7 = compareDist2UUDD(v7)
	v0 = compareDist1UUDD(v0)
	v1 = compareDist1UUDD(v1)
	v2 = compareDist1UUDD(v2)
	v3 = compareDist1UUDD(v3)
	v4 = compareDist1UUDD(v4)
	v5 = compareDist1UUDD(v5)
	v6 = compareDist1UUDD(v6)
	v7 = compareDist1UUDD(v7)

	// Block of 8. Even vectors sort up, odd vectors sort down.
	v0 = compareDist4Up(v0)
	v1 = compareDist4Down(v1)
	v2 = compareDist4Up(v2)
	v3 = compareDist4Down(v3)
	v4 = compareDist4Up(v4)
	v5 = compareDist4Down(v5)
	v6 = compareDist4Up(v6)
	v7 = compareDist4Down(v7)
	v0 = compareDist2Up(v0)
	v1 = compareDist2Down(v1)
	v2 = compareDist2Up(v2)
	v3 = compareDist2Down(v3)
	v4 = compareDist2Up(v4)
	v5 = compareDist2Down(v5)
	v6 = compareDist2Up(v6)
	v7 = compareDist2Down(v7)
	v0 = compareDist1Up(v0)
	v1 = compareDist1Down(v1)
	v2 = compareDist1Up(v2)
	v3 = compareDist1Down(v3)
	v4 = compareDist1Up(v4)
	v5 = compareDist1Down(v5)
	v6 = compareDist1Up(v6)
	v7 = compareDist1Down(v7)

	// Block of 16. Each pair of vectors merges up, down, up, down.
	v0, v1 = compareDist8Up(v0, v1)
	v2, v3 = compareDist8Down(v2, v3)
	v4, v5 = compareDist8Up(v4, v5)
	v6, v7 = compareDist8Down(v6, v7)
	v0 = compareDist4Up(v0)
	v1 = compareDist4Up(v1)
	v2 = compareDist4Down(v2)
	v3 = compareDist4Down(v3)
	v4 = compareDist4Up(v4)
	v5 = compareDist4Up(v5)
	v6 = compareDist4Down(v6)
	v7 = compareDist4Down(v7)
	v0 = compareDist2Up(v0)
	v1 = compareDist2Up(v1)
	v2 = compareDist2Down(v2)
	v3 = compareDist2Down(v3)
	v4 = compareDist2Up(v4)
	v5 = compareDist2Up(v5)
	v6 = compareDist2Down(v6)
	v7 = compareDist2Down(v7)
	v0 = compareDist1Up(v0)
	v1 = compareDist1Up(v1)
	v2 = compareDist1Down(v2)
	v3 = compareDist1Down(v3)
	v4 = compareDist1Up(v4)
	v5 = compareDist1Up(v5)
	v6 = compareDist1Down(v6)
	v7 = compareDist1Down(v7)

	// Block of 32. The low 32 channels merge up and the high 32 merge down.
	v0, v2 = compareDist8Up(v0, v2)
	v1, v3 = compareDist8Up(v1, v3)
	v4, v6 = compareDist8Down(v4, v6)
	v5, v7 = compareDist8Down(v5, v7)
	v0, v1 = compareDist8Up(v0, v1)
	v2, v3 = compareDist8Up(v2, v3)
	v4, v5 = compareDist8Down(v4, v5)
	v6, v7 = compareDist8Down(v6, v7)
	v0 = compareDist4Up(v0)
	v1 = compareDist4Up(v1)
	v2 = compareDist4Up(v2)
	v3 = compareDist4Up(v3)
	v4 = compareDist4Down(v4)
	v5 = compareDist4Down(v5)
	v6 = compareDist4Down(v6)
	v7 = compareDist4Down(v7)
	v0 = compareDist2Up(v0)
	v1 = compareDist2Up(v1)
	v2 = compareDist2Up(v2)
	v3 = compareDist2Up(v3)
	v4 = compareDist2Down(v4)
	v5 = compareDist2Down(v5)
	v6 = compareDist2Down(v6)
	v7 = compareDist2Down(v7)
	v0 = compareDist1Up(v0)
	v1 = compareDist1Up(v1)
	v2 = compareDist1Up(v2)
	v3 = compareDist1Up(v3)
	v4 = compareDist1Down(v4)
	v5 = compareDist1Down(v5)
	v6 = compareDist1Down(v6)
	v7 = compareDist1Down(v7)

	// Block of 64. Merge that bitonic sequence into sorted order, all up.
	v0, v4 = compareDist8Up(v0, v4)
	v1, v5 = compareDist8Up(v1, v5)
	v2, v6 = compareDist8Up(v2, v6)
	v3, v7 = compareDist8Up(v3, v7)
	v0, v2 = compareDist8Up(v0, v2)
	v1, v3 = compareDist8Up(v1, v3)
	v4, v6 = compareDist8Up(v4, v6)
	v5, v7 = compareDist8Up(v5, v7)
	v0, v1 = compareDist8Up(v0, v1)
	v2, v3 = compareDist8Up(v2, v3)
	v4, v5 = compareDist8Up(v4, v5)
	v6, v7 = compareDist8Up(v6, v7)
	v0 = compareDist4Up(v0)
	v1 = compareDist4Up(v1)
	v2 = compareDist4Up(v2)
	v3 = compareDist4Up(v3)
	v4 = compareDist4Up(v4)
	v5 = compareDist4Up(v5)
	v6 = compareDist4Up(v6)
	v7 = compareDist4Up(v7)
	v0 = compareDist2Up(v0)
	v1 = compareDist2Up(v1)
	v2 = compareDist2Up(v2)
	v3 = compareDist2Up(v3)
	v4 = compareDist2Up(v4)
	v5 = compareDist2Up(v5)
	v6 = compareDist2Up(v6)
	v7 = compareDist2Up(v7)
	v0 = compareDist1Up(v0)
	v1 = compareDist1Up(v1)
	v2 = compareDist1Up(v2)
	v3 = compareDist1Up(v3)
	v4 = compareDist1Up(v4)
	v5 = compareDist1Up(v5)
	v6 = compareDist1Up(v6)
	v7 = compareDist1Up(v7)

	v0.Store(data)
	v1.Store(data[8:])
	v2.Store(data[16:])
	v3.Store(data[24:])
	v4.Store(data[32:])
	v5.Store(data[40:])
	v6.Store(data[48:])
	v7.Store(data[56:])
}

// laneReverse8 reverses the eight lanes of one vector.
var laneReverse8 = permIndex([8]int32{7, 6, 5, 4, 3, 2, 1, 0})

// SortingNetwork64RegisterSIMD sorts the 64 int32 channels at the front of data.
// It is the size-64 bitonic sorter with a different first half:
//  1. Each lane is sorted by min/max between the eight vectors, with no shuffles.
//  2. Those eight sorted columns are transposed, using spare vectors as the matrix.
//  3. Odd runs are reversed so the existing 16/32/64 bitonic merges can finish.
func SortingNetwork64RegisterSIMD(data []int32) {
	v0 := archsimd.LoadInt32x8(data)
	v1 := archsimd.LoadInt32x8(data[8:])
	v2 := archsimd.LoadInt32x8(data[16:])
	v3 := archsimd.LoadInt32x8(data[24:])
	v4 := archsimd.LoadInt32x8(data[32:])
	v5 := archsimd.LoadInt32x8(data[40:])
	v6 := archsimd.LoadInt32x8(data[48:])
	v7 := archsimd.LoadInt32x8(data[56:])

	// Vertical bitonic sort. Direction follows the size-8 schedule, applied
	// across vectors so every lane is sorted at once.
	v0, v1 = compareDist8Up(v0, v1)
	v2, v3 = compareDist8Down(v2, v3)
	v4, v5 = compareDist8Up(v4, v5)
	v6, v7 = compareDist8Down(v6, v7)

	v0, v2 = compareDist8Up(v0, v2)
	v1, v3 = compareDist8Up(v1, v3)
	v4, v6 = compareDist8Down(v4, v6)
	v5, v7 = compareDist8Down(v5, v7)

	v0, v1 = compareDist8Up(v0, v1)
	v2, v3 = compareDist8Up(v2, v3)
	v4, v5 = compareDist8Down(v4, v5)
	v6, v7 = compareDist8Down(v6, v7)

	v0, v4 = compareDist8Up(v0, v4)
	v1, v5 = compareDist8Up(v1, v5)
	v2, v6 = compareDist8Up(v2, v6)
	v3, v7 = compareDist8Up(v3, v7)

	v0, v2 = compareDist8Up(v0, v2)
	v1, v3 = compareDist8Up(v1, v3)
	v4, v6 = compareDist8Up(v4, v6)
	v5, v7 = compareDist8Up(v5, v7)

	v0, v1 = compareDist8Up(v0, v1)
	v2, v3 = compareDist8Up(v2, v3)
	v4, v5 = compareDist8Up(v4, v5)
	v6, v7 = compareDist8Up(v6, v7)

	v0, v1, v2, v3, v4, v5, v6, v7 = transpose8x8(v0, v1, v2, v3, v4, v5, v6, v7)
	v1 = v1.Permute(laneReverse8)
	v3 = v3.Permute(laneReverse8)
	v5 = v5.Permute(laneReverse8)
	v7 = v7.Permute(laneReverse8)

	// Block of 16. Each pair of vectors merges up, down, up, down.
	v0, v1 = compareDist8Up(v0, v1)
	v2, v3 = compareDist8Down(v2, v3)
	v4, v5 = compareDist8Up(v4, v5)
	v6, v7 = compareDist8Down(v6, v7)
	v0 = compareDist4Up(v0)
	v1 = compareDist4Up(v1)
	v2 = compareDist4Down(v2)
	v3 = compareDist4Down(v3)
	v4 = compareDist4Up(v4)
	v5 = compareDist4Up(v5)
	v6 = compareDist4Down(v6)
	v7 = compareDist4Down(v7)
	v0 = compareDist2Up(v0)
	v1 = compareDist2Up(v1)
	v2 = compareDist2Down(v2)
	v3 = compareDist2Down(v3)
	v4 = compareDist2Up(v4)
	v5 = compareDist2Up(v5)
	v6 = compareDist2Down(v6)
	v7 = compareDist2Down(v7)
	v0 = compareDist1Up(v0)
	v1 = compareDist1Up(v1)
	v2 = compareDist1Down(v2)
	v3 = compareDist1Down(v3)
	v4 = compareDist1Up(v4)
	v5 = compareDist1Up(v5)
	v6 = compareDist1Down(v6)
	v7 = compareDist1Down(v7)

	// Block of 32. The low 32 channels merge up and the high 32 merge down.
	v0, v2 = compareDist8Up(v0, v2)
	v1, v3 = compareDist8Up(v1, v3)
	v4, v6 = compareDist8Down(v4, v6)
	v5, v7 = compareDist8Down(v5, v7)
	v0, v1 = compareDist8Up(v0, v1)
	v2, v3 = compareDist8Up(v2, v3)
	v4, v5 = compareDist8Down(v4, v5)
	v6, v7 = compareDist8Down(v6, v7)
	v0 = compareDist4Up(v0)
	v1 = compareDist4Up(v1)
	v2 = compareDist4Up(v2)
	v3 = compareDist4Up(v3)
	v4 = compareDist4Down(v4)
	v5 = compareDist4Down(v5)
	v6 = compareDist4Down(v6)
	v7 = compareDist4Down(v7)
	v0 = compareDist2Up(v0)
	v1 = compareDist2Up(v1)
	v2 = compareDist2Up(v2)
	v3 = compareDist2Up(v3)
	v4 = compareDist2Down(v4)
	v5 = compareDist2Down(v5)
	v6 = compareDist2Down(v6)
	v7 = compareDist2Down(v7)
	v0 = compareDist1Up(v0)
	v1 = compareDist1Up(v1)
	v2 = compareDist1Up(v2)
	v3 = compareDist1Up(v3)
	v4 = compareDist1Down(v4)
	v5 = compareDist1Down(v5)
	v6 = compareDist1Down(v6)
	v7 = compareDist1Down(v7)

	// Block of 64. Merge that bitonic sequence into sorted order, all up.
	v0, v4 = compareDist8Up(v0, v4)
	v1, v5 = compareDist8Up(v1, v5)
	v2, v6 = compareDist8Up(v2, v6)
	v3, v7 = compareDist8Up(v3, v7)
	v0, v2 = compareDist8Up(v0, v2)
	v1, v3 = compareDist8Up(v1, v3)
	v4, v6 = compareDist8Up(v4, v6)
	v5, v7 = compareDist8Up(v5, v7)
	v0, v1 = compareDist8Up(v0, v1)
	v2, v3 = compareDist8Up(v2, v3)
	v4, v5 = compareDist8Up(v4, v5)
	v6, v7 = compareDist8Up(v6, v7)
	v0 = compareDist4Up(v0)
	v1 = compareDist4Up(v1)
	v2 = compareDist4Up(v2)
	v3 = compareDist4Up(v3)
	v4 = compareDist4Up(v4)
	v5 = compareDist4Up(v5)
	v6 = compareDist4Up(v6)
	v7 = compareDist4Up(v7)
	v0 = compareDist2Up(v0)
	v1 = compareDist2Up(v1)
	v2 = compareDist2Up(v2)
	v3 = compareDist2Up(v3)
	v4 = compareDist2Up(v4)
	v5 = compareDist2Up(v5)
	v6 = compareDist2Up(v6)
	v7 = compareDist2Up(v7)
	v0 = compareDist1Up(v0)
	v1 = compareDist1Up(v1)
	v2 = compareDist1Up(v2)
	v3 = compareDist1Up(v3)
	v4 = compareDist1Up(v4)
	v5 = compareDist1Up(v5)
	v6 = compareDist1Up(v6)
	v7 = compareDist1Up(v7)

	v0.Store(data)
	v1.Store(data[8:])
	v2.Store(data[16:])
	v3.Store(data[24:])
	v4.Store(data[32:])
	v5.Store(data[40:])
	v6.Store(data[48:])
	v7.Store(data[56:])
}

// transpose8x8 turns columns into rows. v0[i]..v7[i] become row i.
func transpose8x8(r0, r1, r2, r3, r4, r5, r6, r7 archsimd.Int32x8) (archsimd.Int32x8, archsimd.Int32x8, archsimd.Int32x8, archsimd.Int32x8, archsimd.Int32x8, archsimd.Int32x8, archsimd.Int32x8, archsimd.Int32x8) {
	t0 := r0.InterleaveLoGrouped(r1)
	t1 := r0.InterleaveHiGrouped(r1)
	t2 := r2.InterleaveLoGrouped(r3)
	t3 := r2.InterleaveHiGrouped(r3)
	t4 := r4.InterleaveLoGrouped(r5)
	t5 := r4.InterleaveHiGrouped(r5)
	t6 := r6.InterleaveLoGrouped(r7)
	t7 := r6.InterleaveHiGrouped(r7)

	u0 := t0.ConcatPermuteScalarsGrouped(0, 1, 4, 5, t2)
	u1 := t1.ConcatPermuteScalarsGrouped(0, 1, 4, 5, t3)
	u2 := t0.ConcatPermuteScalarsGrouped(2, 3, 6, 7, t2)
	u3 := t1.ConcatPermuteScalarsGrouped(2, 3, 6, 7, t3)
	u4 := t4.ConcatPermuteScalarsGrouped(0, 1, 4, 5, t6)
	u5 := t5.ConcatPermuteScalarsGrouped(0, 1, 4, 5, t7)
	u6 := t4.ConcatPermuteScalarsGrouped(2, 3, 6, 7, t6)
	u7 := t5.ConcatPermuteScalarsGrouped(2, 3, 6, 7, t7)

	return u0.ConcatPermute128Scalars(0, 2, u4),
		u2.ConcatPermute128Scalars(0, 2, u6),
		u1.ConcatPermute128Scalars(0, 2, u5),
		u3.ConcatPermute128Scalars(0, 2, u7),
		u0.ConcatPermute128Scalars(1, 3, u4),
		u2.ConcatPermute128Scalars(1, 3, u6),
		u1.ConcatPermute128Scalars(1, 3, u5),
		u3.ConcatPermute128Scalars(1, 3, u7)
}
